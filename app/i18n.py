def normalize_lang(value: str | None) -> str:
    raw = (value or "").strip().lower().replace("_", "-")
    if raw.startswith("en"):
        return "en"
    return "fr"


def lang_of(request: Request | None) -> str:
    if request is None:
        return "fr"
    q = request.query_params.get("lang")
    if q:
        return normalize_lang(q)
    cookie = request.cookies.get(COOKIE)
    if cookie:
        return normalize_lang(cookie)
    accept = request.headers.get("accept-language") or ""
    for part in accept.split(","):
        tag = part.split(";")[0].strip()
        if tag.lower().startswith("en"):
            return "en"
        if tag.lower().startswith("fr"):
            return "fr"
    return "fr"


def t(lang: str, key: str, **kwargs: Any) -> str:
    table = STRINGS.get(normalize_lang(lang)) or STRINGS["fr"]
    text = table.get(key) or STRINGS["fr"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def dump(lang: str) -> dict[str, str]:
    return dict(STRINGS.get(normalize_lang(lang)) or STRINGS["fr"])
